"""Scene report (docs/templates/scene_report.md format): changes, geometry with uncertainty,
robot interactability and simulator randomisation ranges, generated from one analysis."""

from __future__ import annotations


def _rng(a, b):
    return f"{a:.1f} to {b:.1f}"


def write(path, spec_name: str, a: str, b: str, m: dict, objs: list, f: dict | None, fstats: dict | None,
          lighting_note: str) -> None:
    fl = f["floor"] if f else None
    L = [f"# Scene report: {a} vs {b}", "", f"Generated by step `{spec_name}`.", "",
         "| | |", "|---|---|",
         f"| Recordings | `{a}` (before), `{b}` (after) |",
         f"| Lighting | {lighting_note} |",
         f"| Alignment residual (across / within recordings) | {m.get('alignment_residual_cross')} / {m.get('alignment_residual_within')} (relative depth) |",
         f"| Observed in both recordings | {m.get('A_observed_frac', 0):.0%} of A, {m.get('B_observed_frac', 0):.0%} of B |"]
    if fl:
        L.append(f"| Metric scale | {fl['scale_m_per_unit']:.3f} m per unit (range {fl['scale_range'][0]:.3f}-"
                 f"{fl['scale_range'][1]:.3f}, from phone height {f['robot']['phone_height_m']} m, floor fit "
                 f"{fl['inlier_frac']:.0%} inliers) |")
    L += ["", "## 1. Changes", "", "| # | Object | Change | Size (cm) | Moved (cm, 90% CI) | Position sd (cm) | Confidence | Description |",
          "|---|---|---|---|---|---|---|---|"]
    seen = set()
    for o in sorted(objs, key=lambda o: -o.n_points):
        if o.id in seen or o.extra.get("is_background"):
            continue
        seen |= {o.id, o.partner}
        mt = o.extra.get("metric", {})
        size = " x ".join(f"{x:.0f}" for x in mt.get("size_cm", [])) or "-"
        mv = (f"{mt['distance_cm']:.0f} ({_rng(*mt['distance_cm_ci'])})" if "distance_cm" in mt else "-")
        L.append(f"| {o.id} | {o.label} | {o.kind} | {size} | {mv} | {mt.get('position_sd_cm', '-')} | "
                 f"{o.label_prob} | {o.description} |")
    bg = [o for o in objs if o.extra.get("is_background")]
    if bg:
        L += ["", f"{len(bg)} further detections were labelled as background (floor, wall, sofa...) and are "
              "most likely reconstruction artefacts; they are listed in changes.json."]

    L += ["", "## 2. Object geometry with uncertainty", "",
          "| Object | Size (cm) | 90% bootstrap interval per axis | Including scale uncertainty | Boundary uncertainty (cm) | Mean surface shift (cm) |",
          "|---|---|---|---|---|---|"]
    for o in objs:
        mt = o.extra.get("metric")
        if not mt or o.extra.get("is_background"):
            continue
        ci = "; ".join(_rng(lo, hi) for lo, hi in mt["size_cm_ci"])
        sr = " / ".join(f"{lo:.0f}-{hi:.0f}" for lo, hi in zip(*mt["size_cm_scale_range"]))
        L.append(f"| {o.id} {o.label} | {' x '.join(f'{x:.0f}' for x in mt['size_cm'])} | {ci} | {sr} | "
                 f"{mt['boundary_uncertainty_cm']} | {mt['mean_abs_shift_cm']} |")

    if f and fstats:
        r = f["robot"]
        L += ["", "## 3. Robot interactability", "",
              f"- Assumed robot: base on the floor where the camera operator stood, arm mount at "
              f"{r['shoulder_height_m']} m, reach {r['reach_m']} m, gripper needs {r['gripper_clearance_m'] * 100:.0f} cm "
              f"of free space (radius {r['gripper_radius_m'] * 100:.0f} cm).",
              f"- Reachable surface: {fstats['reachable_frac']:.0%}; approachable: {fstats['approachable_frac']:.0%}; "
              f"interactable (both, with certain geometry): {fstats['interactable_frac']:.0%}.",
              "- Heat maps: `heatmaps.png`, layers in `viewer.html`, fields in `fields.ply`."]
        if fstats.get("base_best_score") is not None:
            L += [f"- Best place to stand (`base_placement.png`): {fstats['base_best_from_operator_m']} m from where "
                  f"the camera operator stood; reaches {fstats['base_best_score']:.0%} of surfaces"
                  + (f" and {fstats['base_best_score_changed']:.0%} of changed surfaces"
                     if fstats.get("base_best_score_changed") is not None else "")
                  + f". The robot fits on {fstats['base_standable_frac']:.0%} of the observed floor grid."]
        L += ["",
              "| Object | Reach (0-1) | Approach (0-1) | Height (m) |", "|---|---|---|---|"]
        for o in objs:
            mt = o.extra.get("metric")
            if mt and not o.extra.get("is_background"):
                L.append(f"| {o.id} {o.label} | {mt['reach']} | {mt['approach']} | {mt['height_m']} |")
        L += ["", "Changed areas should be re-checked by the robot before acting there."]

    L += ["", "## 4. Simulator randomisation recommendations", "",
          "| Parameter | Nominal | Randomise over | Distribution | Why |", "|---|---|---|---|---|"]
    for o in objs:
        mt = o.extra.get("metric")
        if not mt or o.extra.get("is_background"):
            continue
        for ax, (nom, (lo, hi)) in enumerate(zip(mt["size_cm"], mt["size_cm_ci"])):
            lo2 = min(lo, nom * fl["scale_range"][0] / fl["scale_m_per_unit"]) if fl else lo
            hi2 = max(hi, nom * fl["scale_range"][1] / fl["scale_m_per_unit"]) if fl else hi
            L.append(f"| {o.label} size axis {ax + 1} | {nom:.1f} cm | {lo2:.1f} to {hi2:.1f} cm | uniform | "
                     "bootstrap spread of the reconstruction and scale uncertainty |")
        L.append(f"| {o.label} position | as reconstructed | +/- {2 * mt['position_sd_cm']:.1f} cm | normal "
                 f"(sd {mt['position_sd_cm']:.1f} cm) | centroid uncertainty |")
        if o.kind == "moved":
            L.append(f"| {o.label} placement | both observed poses | between them | uniform over the segment | "
                     "the object is known to be moved by people |")
        if o.kind == "appearance":
            L.append(f"| {o.label} shape / orientation | observed | flipped or deformed variants | discrete + "
                     "deformation | appearance changed in place (deformable or turned over) |")
    if fstats:
        L.append(f"| Global surface noise | 0 | +/- {fstats['uncertainty_cm_p90']} cm | normal | 90th percentile of "
                 "per-point uncertainty |")
    L.append(f"| Lighting | {lighting_note} | both conditions | categorical + intensity jitter | recordings in "
             "different light showed how much appearance shifts |")
    L += ["", "## 5. Known limitations", "",
          "- Metric scale assumes the phone height; distances scale with it (range given).",
          "- No ground truth yet: these detections are unscored; static and lighting-only pairs measure the "
          "false-change rate.",
          "- Labels come from a zero-shot CLIP model on crops and may be wrong for unusual objects."]
    with open(path, "w") as fh:
        fh.write("\n".join(L) + "\n")
